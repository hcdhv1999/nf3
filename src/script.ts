/*
 * ============================================================
 *  نص الفيديو وتوقيتاته — هذا هو الملف الوحيد الذي تحتاج تعديله
 * ============================================================
 *
 *  • كل الأوقات بالثواني من بداية الفيديو (وليس من بداية المشهد).
 *    مثال: from: 9.6 تعني أن النص يظهر عند الثانية 9.6 من الفيديو.
 *  • from = وقت الظهور، to = وقت الاختفاء.
 *  • لا تجعل أي نص يظهر أقل من 1.8 ثانية (to - from >= 1.8).
 *    شغّل الأمر:  npm run check  للتأكد من سلامة التوقيتات بعد أي تعديل.
 *  • النصوص بين علامتي التنصيص '...' فقط — لا تحذف الفواصل أو الأقواس.
 *  • vo: نص التعليق الصوتي للمشهد (للمرجع)، و from/to هما فترة الكلام،
 *    وتُستخدم لخفض صوت الموسيقى تلقائيًا أثناء التعليق.
 *  • images / categories: أسماء صور من ملف src/assets.ts
 *    (والصور نفسها توضع في public/assets/).
 */

/** سطر نصي يظهر داخل لوح أخضر داكن */
export type Line = {
  /** النص المعروض */
  text: string;
  /** وقت الظهور (ثانية) */
  from: number;
  /** وقت الاختفاء (ثانية) */
  to: number;
  /** الحجم: صغير 'sm' — متوسط 'md' — كبير 'lg' — ضخم 'xl' */
  size?: 'sm' | 'md' | 'lg' | 'xl';
};

export type Scene = {
  /** رمز المشهد — لا تغيّره */
  id: 'S1' | 'S2' | 'S3' | 'S4' | 'S5' | 'S6' | 'S7' | 'S8';
  /** بداية المشهد ونهايته بالثواني */
  from: number;
  to: number;
  /** التعليق الصوتي: النص وفترة الكلام */
  vo: {text: string; from: number; to: number};
  /** ألواح النص في المشهد */
  lines: Line[];
  /** صور المشهد (S1: صورة لكل سطر بالترتيب — S2: صورة واحدة) */
  images?: string[];
  /** خطوات المشهد الرابع */
  steps?: {title: string; icon: 'verify' | 'camera' | 'booking' | 'handover'; at: number}[];
  /** المشهد الخامس: تقسيم الإيراد */
  split?: {
    at: number;
    right: {label: string; percent: number};
    left: {label: string; percent: number};
    /** رمز النسبة المئوية */
    suffix: string;
  };
  /** المشهد السادس: الفئات (صورة + اسم) بالترتيب */
  categories?: {asset: string; label: string; from: number; to: number}[];
};

